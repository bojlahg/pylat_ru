def test_totals_are_consistent_and_complete(inventory: dict) -> None:
    totals = inventory["totals"]
    closure = inventory["contract_closure"]
    assert totals["russian_module_test_files_total"] == 18
    assert totals["russian_module_test_files_accounted"] == 18
    assert totals["executable_methods_total"] == totals["executable_methods_mapped"] == 24
    assert totals["contract_closure_total"] == len(closure)
    assert totals["contract_scenario_units_total"] == sum(r["scenario_units"] for r in closure)
    assert totals["contract_assertion_units_total"] == sum(r["assertion_units"] for r in closure)
    assert totals["blocked"] == 0
    assert totals["unmapped"] == 0
    assert totals["unknown"] == 0
    assert totals["ordinary_non_lm_contracts_total"] == totals["ordinary_non_lm_contracts_mapped"]
    assert (totals["ordinary_non_lm_scenario_units_total"]
            == totals["ordinary_non_lm_scenario_units_mapped"])
    assert totals["generic_core_evidence_sources_total"] == 13
    assert (totals["generic_core_evidence_sources_reconciled"]
            == totals["generic_core_evidence_sources_total"])
    counts = totals["status_counts"]
    assert set(counts) == ALLOWED_STATUS
    assert sum(counts.values()) == len(closure)
    assert counts["BLOCKED"] == 0
    assert counts["LANGUAGE_MODEL_DEFERRED"] == 1


